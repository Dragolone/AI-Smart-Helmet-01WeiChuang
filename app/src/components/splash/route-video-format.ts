// 预渲染成视频的路线段（assets/splash/route-video.mp4）的几个约定，录制脚本和播放两边共用。
//
// 安卓上播的是它。路线那一段带着好几层全屏模糊和几千条小路径，安卓这一档的显卡逐帧现画跟不上：
// 华为 P30 Pro 上播矢量的预录帧，一帧要 50 毫秒上下，分辨率降到三分之一还要 25 毫秒（2026-10-08 实测）。
// 所以先在电脑上把每一帧画成像素、压成视频，手机上交给系统的播放器（expo-video，解码在它自己的线程里）。
// 试过 Skia 自带的视频对象：它要在主线程上一帧一帧同步地等解码器（每帧 5–10 毫秒），华为照样掉到 30 帧。
// iOS 仍然播矢量的预录帧（route-frames.skpack），那边是流畅的，而且更清晰。

/** 每秒帧数，和矢量的预录帧一致 */
export const VIDEO_FPS = 60;
/** 视频一帧的大小（像素）。竖着的 720 × 1840：比哪种手机都高，播放时铺满宽度、上下居中裁掉 */
export const VIDEO_W = 720;
export const VIDEO_H = 1840;
/** 画面有多高（宽固定 282 个单位） */
export const VIDEO_SCENE_H = (VIDEO_H / VIDEO_W) * 282;
/** 正片前垫的几帧（和第一帧一样）：播放器起步要一点时间，垫着的这段里开屏的时钟还没开始走 */
export const VIDEO_PRE = 12;
/**
 * 正片后垫的几帧（和最后一帧一样）。只垫 0.1 秒：视频放完会自己停在最后一帧上，画布早一点晚一点接手都是同一个画面；
 * 而它放完解码器也就歇了——商标成形之后正是页面上重的内容搭起来的时候，那时还开着解码器会多卡几帧
 * （模拟器上量过；靠 JS 去叫停不可靠，那一刻 JS 正忙）
 */
export const VIDEO_POST = 6;
/** 垫片有多长（毫秒） */
export const VIDEO_PRE_MS = (VIDEO_PRE * 1000) / VIDEO_FPS;
/** 商标完成时画布用这么久（故事时间，毫秒）淡进来，接过视频的最后一帧（两边是同一个画面） */
export const VIDEO_HANDOVER = 50;
